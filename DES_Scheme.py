def des_process(text: str, key64: int, mode: str = "encrypt", cipher_blocks: list[int] = None):
# cipher_blocks will hold a list of the intermediate encrypted blocks during processing and the key has to be 64 bits because DES uses a 64-bit key with 8 parity bits.


    # Permutation, Expansion, and S-Box tables for this function.
    E = [32, 1, 2, 3, 4, 5, 4, 5, 6, 7, 8, 9, 8, 9, 10, 11, 12, 13,
         12, 13, 14, 15, 16, 17, 16, 17, 18, 19, 20, 21, 20, 21, 22, 23, 24, 25,
         24, 25, 26, 27, 28, 29, 28, 29, 30, 31, 32, 1]

    P = [16, 7, 20, 21, 29, 12, 28, 17, 1, 15, 23, 26, 5, 18, 31, 10,
        2, 8, 24, 14, 32, 27, 3, 9, 19, 13, 30, 6, 22, 11, 4, 25]

    S_BOX = [
        [14, 4, 13, 1, 2, 15, 11, 8, 3, 10, 6, 12, 5, 9, 0, 7],
        [0, 15, 7, 4, 14, 2, 13, 1, 10, 6, 12, 11, 9, 5, 3, 8],
        [4, 1, 14, 8, 13, 6, 2, 11, 15, 12, 9, 7, 3, 10, 5, 0],
        [15, 12, 8, 2, 4, 9, 1, 7, 5, 11, 3, 14, 10, 0, 6, 13]
    ]

    #make 56-bit key from 64-bit key (stripping bits)
    key56 = 0
    for i in range(64):
        if (i + 1) % 8 != 0:
            key56 = (key56 << 1) | ((key64 >> (63 - i)) & 1) #this strips the parity bits thingy from the 64-bit key into a 56-bit key.
            #Example if key64 = 0x0123456789ABCDEF, the parity bits (every 8th bit) will be stripped to form key56 = 0x0123456789ABCD.

    #This is hexadecimal because the subkeys are generated using a fixed pattern in hex (0x0F0F0F0F0F0F) and we want to keep them in a consistent 48-bit format.
    subkeys = [(key56 ^ (i * 0x0F0F0F0F0F0F)) & 0xFFFFFFFFFFFF for i in range(16)] # XOR with a pattern to generate subkeys until we have 16 of them.
    #Example: If key56 = 0x0123456789ABCD, the subkeys will be generated by XORing with the pattern 0x0F0F0F0F0F0F for each round. which results in 16 different 48-bit subkeys.
    #Because wow we have all the keys needed for the 16 Feistel rounds already generated.

    if mode == "decrypt":
        subkeys = subkeys[::-1]  # Reversing subkey order for decryption :D

    #Permutation thing
    def permute(block, table, input_size):
        res = 0
        for idx, pos in enumerate(table): #This for loop applies the permutation table to the block until all bits are rearranged according to the table.
            bit = (block >> (input_size - pos)) & 1  # Extract the bit at the position specified by the permutation table.
            res |= bit << (len(table) - 1 - idx)  # Place the extracted bit in the correct position according to the permutation table.
        return res

    #Encrypting time!
    if mode == "encrypt":
        # Pad to 8-byte boundary (multiple of 8 bytes)
        padded = text.ljust((len(text) + 7) // 8 * 8, ' ') #pading is done with spaces to make the text a multiple of 8 bytes like if its 64-bit aligned then it will fit perfectly into 8-byte blocks.
        #For example, if the text is "HELLO", it will be padded to "HELLO   " to make it 8 bytes long.
        raw_bytes = padded.encode('ascii') #this is just converting the padded text into bytes for further processing.
        
        output_blocks = []
        for i in range(0, len(raw_bytes), 8):
            block_int = int.from_bytes(raw_bytes[i:i+8], 'big') #Convert the 8-byte chunk into a 64-bit integer for processing in the Feistel rounds.
            
            # Split into left & right halves (32 bits each)
            left, right = (block_int >> 32) & 0xFFFFFFFF, block_int & 0xFFFFFFFF
            
            # 16 Feistel rounds (Cuz why would it be 16)
            for subkey in subkeys:
                expanded = permute(right, E, 32) ^ subkey #this is the expansion permutation and XOR with the subkey. All in one
                s_out = 0
                for s_idx in range(8):
                    chunk6 = (expanded >> (42 - s_idx * 6)) & 0x3F # Extract 6-bit chunk for S-box lookup as in shift expanded right by 6 bits for each S-box input.
                    row = ((chunk6 >> 5) & 1) << 1 | (chunk6 & 1)  # Determine the row for the S-box lookup
                    col = (chunk6 >> 1) & 0x0F  # Determine the column for the S-box lookup
                    #All this is worked with binary operations to extract the correct row and column for the S-box lookup.

                    s_out = (s_out << 4) | S_BOX[row][col] 
                f_res = permute(s_out, P, 32) #All this just for 1 Feistel round result....
                
                left, right = right, left ^ f_res
                
            enc_block = (right << 32) | left # Combine the left and right halves back into a 64-bit block after the Feistel rounds.
            output_blocks.append(enc_block) #We have the block :D

        hex_output = "".join(f"{b:016X}" for b in output_blocks) #Actual encrypted output in hexadecimal
        return hex_output, output_blocks

    #Decrypting time!
    elif mode == "decrypt":
        decrypted_bytes = bytearray() #This will hold the decrypted bytes as we process each 64-bit block.
        for block_int in cipher_blocks:
            left, right = (block_int >> 32) & 0xFFFFFFFF, block_int & 0xFFFFFFFF
            
            # 16 Feistel rounds

            #This is literally just the same as encrypting but going backwards from 1 to 16 we go here from 16 to 1
            for subkey in subkeys:
                expanded = permute(right, E, 32) ^ subkey
                s_out = 0
                for s_idx in range(8):
                    chunk6 = (expanded >> (42 - s_idx * 6)) & 0x3F
                    row = ((chunk6 >> 5) & 1) << 1 | (chunk6 & 1)
                    col = (chunk6 >> 1) & 0x0F
                    s_out = (s_out << 4) | S_BOX[row][col]
                f_res = permute(s_out, P, 32)
                
                left, right = right, left ^ f_res
                
            dec_block = (right << 32) | left
            decrypted_bytes.extend(dec_block.to_bytes(8, 'big'))
        
        return decrypted_bytes.decode('ascii')



